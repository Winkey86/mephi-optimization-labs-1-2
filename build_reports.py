"""Build editable academic reports and Markdown from the computed result files."""
import csv
import json
from pathlib import Path
from docx import Document
from docx.shared import Cm, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT, WD_CELL_VERTICAL_ALIGNMENT
from docx.oxml import OxmlElement
from docx.oxml.ns import qn

ROOT=Path(__file__).resolve().parent
AUTHOR='Песковацков Илья Александрович'
GROUP='Б24-517'


def read(i,name='summary'):
    return json.loads((ROOT/f'lab{i}/results/{name}.json').read_text())


def data(i):
    return json.loads((ROOT/f'lab{i}/data/variant.json').read_text())


def records(i,name):
    with (ROOT/f'lab{i}/results/{name}.csv').open(encoding='utf-8-sig') as f:
        return list(csv.DictReader(f))


def f(x,n=2):
    return f'{float(x):,.{n}f}'.replace(',',' ').replace('.',',')


class Report:
    def __init__(self,i,subject):
        self.i=i;self.md=[];self.doc=Document()
        sec=self.doc.sections[0]
        sec.page_width=Cm(21);sec.page_height=Cm(29.7)
        sec.left_margin=Cm(2.1);sec.right_margin=Cm(2.1)
        sec.top_margin=Cm(1.7);sec.bottom_margin=Cm(1.8)
        sec.header_distance=Cm(.6);sec.footer_distance=Cm(.7)
        for name in ['Normal','Title','Subtitle','Heading 1','Heading 2','Caption']:
            s=self.doc.styles[name];s.font.name='Times New Roman';s.font.color.rgb=RGBColor(0,0,0)
            fonts=s.element.get_or_add_rPr().rFonts
            for attr in list(fonts.attrib):
                if attr.endswith('Theme'):del fonts.attrib[attr]
            for attr in ['ascii','hAnsi','eastAsia','cs']:fonts.set(qn('w:'+attr),'Times New Roman')
        s=self.doc.styles['Normal'];s.font.size=Pt(11.5)
        s.paragraph_format.space_after=Pt(5);s.paragraph_format.line_spacing=1.06
        for name,size in [('Title',17),('Heading 1',13),('Heading 2',11.5)]:
            s=self.doc.styles[name];s.font.size=Pt(size);s.font.bold=True
            s.paragraph_format.space_before=Pt(10);s.paragraph_format.space_after=Pt(5)
            s.paragraph_format.keep_with_next=True
        s=self.doc.styles['Caption'];s.font.size=Pt(9.5);s.font.italic=True
        footer=sec.footer.paragraphs[0];footer.alignment=WD_ALIGN_PARAGRAPH.CENTER
        r=footer.add_run();field=OxmlElement('w:fldSimple');field.set(qn('w:instr'),'PAGE');r._r.addnext(field)
        p=self.doc.add_paragraph();p.alignment=WD_ALIGN_PARAGRAPH.RIGHT
        r=p.add_run(f'Выполнил студент группы {GROUP}\n{AUTHOR}\nНомер в группе 19   Вариант 17\n2026 год')
        r.font.size=Pt(10)
        self.md.extend([f'# Лабораторная работа {i}',f'## {subject}',
                        f'{AUTHOR}, {GROUP}. Номер в группе 19. Вариант 17. 2026 год.'])
        self.doc.add_paragraph(f'Лабораторная работа {i}',style='Title')
        p=self.doc.add_paragraph(subject);p.runs[0].bold=True;p.runs[0].font.size=Pt(13)
        self.p('Дисциплина «Методы оптимизации. Линейное программирование». '
               'Работа выполнена по комплексу лабораторных работ А. А. Кузьмина на 2026 год.')

    def p(self,text):
        p=self.doc.add_paragraph(text);p.paragraph_format.keep_together=True;self.md.append(text)

    def h(self,text,level=1):
        self.doc.add_heading(text,level);self.md.append('#'*(level+1)+' '+text)

    def eq(self,text):
        p=self.doc.add_paragraph();p.alignment=WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_before=Pt(3);p.paragraph_format.space_after=Pt(6)
        r=p.add_run(text);r.italic=True;r.font.name='Cambria Math';r.font.size=Pt(11)
        self.md.append(text)

    def table(self,headers,rows,widths=None):
        rows=[list(map(str,row)) for row in rows]
        table=self.doc.add_table(rows=1,cols=len(headers));table.alignment=WD_TABLE_ALIGNMENT.CENTER
        table.autofit=False
        widths=widths or [16.8/len(headers)]*len(headers)
        for j,column in enumerate(table.columns):column.width=Cm(widths[j])
        for j,h in enumerate(headers):table.rows[0].cells[j].text=h
        for row in rows:
            cells=table.add_row().cells
            for j,val in enumerate(row):cells[j].text=val
        for rowidx,row in enumerate(table.rows):
            trPr=row._tr.get_or_add_trPr();cant=OxmlElement('w:cantSplit');trPr.append(cant)
            if rowidx==0:
                repeat=OxmlElement('w:tblHeader');trPr.append(repeat)
            for j,cell in enumerate(row.cells):
                cell.width=Cm(widths[j]);cell.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
                for p in cell.paragraphs:
                    p.paragraph_format.space_after=Pt(3);p.paragraph_format.space_before=Pt(3)
                    p.paragraph_format.line_spacing=1
                    p.alignment=WD_ALIGN_PARAGRAPH.LEFT if j==0 else WD_ALIGN_PARAGRAPH.CENTER
                    for r in p.runs:r.font.size=Pt(9.5);r.bold=rowidx==0
                if rowidx==0:
                    shade=OxmlElement('w:shd');shade.set(qn('w:fill'),'EEEEEE');cell._tc.get_or_add_tcPr().append(shade)
        borders=OxmlElement('w:tblBorders')
        for key in ['top','bottom','insideH']:
            e=OxmlElement('w:'+key);e.set(qn('w:val'),'single');e.set(qn('w:sz'),'4');e.set(qn('w:color'),'AAAAAA');borders.append(e)
        table._tbl.tblPr.append(borders)
        self.doc.add_paragraph().paragraph_format.space_after=Pt(0)
        cells=lambda row:[str(v).replace('\n','<br>').replace('|','\\|') for v in row]
        markdown=['| '+' | '.join(cells(headers))+' |','| '+' | '.join(['---']*len(headers))+' |']
        markdown.extend('| '+' | '.join(cells(row))+' |' for row in rows)
        self.md.append('\n'.join(markdown))

    def image(self,file,caption,width=16.5):
        p=self.doc.add_paragraph();p.alignment=WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.keep_with_next=True
        p.add_run().add_picture(str(ROOT/f'lab{self.i}/results/{file}'),width=Cm(width))
        p=self.doc.add_paragraph(caption,style='Caption');p.alignment=WD_ALIGN_PARAGRAPH.CENTER
        self.md.append(f'![{caption}](results/{file})')

    def page(self):
        self.doc.add_page_break()

    def common_variant(self):
        self.p('Индивидуальные параметры: N = 19; для группы 517 индекс Q = 1; Y = 26. '
               'V = 1 + ((17·19 + 7·1 + 26) mod 20) = 1 + 16 = 17. '
               'Seed = 10000 + 100·1 + 19 = 10119. Данные синтетические, учебные; '
               'фактические характеристики организаций и оборудования не использовались.')

    def implementation(self,filename):
        self.h('Реализация и воспроизводимость')
        if self.i==1:
            self.p('Процедура генерации PCG64(10119): сначала A = integers(1,7,(3,8))/10; '
                   'затем d = integers(12,25,8); b = round(A·(0,45d),2); '
                   'далее c = integers(300,701,8). Договорные минимумы l = (5;4;3;0;0;0;0;0) '
                   'заданы явно. Верхняя граница integers исключена. Реальные входные числа '
                   'сохранены в JSON, повторная генерация не нужна для обычного запуска.')
        self.p(f'Модель реализована в {filename}; общий интерфейс HiGHS — common.py; '
          'данные — data/variant.json; генератор — generate_data.py. Функции загрузки, '
          'построения или формирования матриц, решения, независимой проверки и отчётности разделены. '
          'Одна команда из корня комплекта: python run_all.py. Повторная генерация и расчёт: '
          'python run_all.py --generate. Для отдельной работы: python '+filename+'.')
        self.p('Среда расчёта: Python 3.12.14; highspy и HiGHS 1.15.1; NumPy 2.3.5; '
          'matplotlib 3.11.2. Версии закреплены в requirements.txt; среда и архитектура — environment.json. '
          'Один поток; random_seed = 10119; presolve включён; лимит решения 120 с; '
          'primal/dual feasibility tolerance = 10⁻⁸; mip feasibility tolerance = 10⁻⁸; '
          'mip_rel_gap = 0. Независимая проверка использует допуск 10⁻⁷.')
        self.p('ЛП решаются симплекс-методом HiGHS; в сравнительном эксперименте используется IPM '
          'с crossover. MILP решаются встроенным методом ветвей и границ с отсечениями. '
          'Время измерено time.perf_counter вокруг h.run без построения модели, чтения данных и графиков. '
          'Замеры отражают данную машину и не являются гарантией производительности.')

    def sources(self):
        self.h('Источники и сдаваемые материалы')
        self.p('1. Кузьмин А. А. Дисциплина «Методы оптимизации. Линейное программирование». '
               'Комплекс лабораторных работ, 2026. Предоставленный файл DOCX; общие требования и вариант 17.')
        self.p('2. HiGHS. Официальный интерфейс Python, модели, статусы и логи: '
               'https://github.com/ergo-code/highs/blob/master/docs/src/interfaces/python/example-py.md')
        self.p('3. HiGHS. Параметры решателя: https://ergo-code.github.io/HiGHS/stable/options/definitions/ . '
               'Использован открытый решатель, проприетарные компоненты отсутствуют.')
        self.p('В папке работы находятся report.pdf, report.md, data/variant.json, README.md и results/. '
               'В results/ сохранены реальные логи *.log, модели *.lp, CSV решений и сценариев, '
               'summary.json, verification.json и графики PNG. Исходники и requirements.txt находятся '
               'в корне репозитория GitHub. Отчёт представлен в PDF для сдачи и в Markdown '
               'для просмотра на GitHub. Код, данные и результаты опубликованы вместе с отчётом.')

    def save(self):
        folder=ROOT/f'lab{self.i}'
        for border in self.doc.styles['Title'].element.xpath('.//w:pBdr'):
            border.getparent().remove(border)
        self.doc.core_properties.author=AUTHOR
        self.doc.core_properties.title=f'Лабораторная работа {self.i} Вариант 17'
        self.doc.core_properties.subject='Методы оптимизации Линейное программирование'
        self.doc.save(folder/'report.docx')
        (folder/'report.md').write_text('\n\n'.join(self.md)+'\n',encoding='utf-8')


